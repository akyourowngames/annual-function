import {chromium} from '@playwright/test';
import fs from 'node:fs';
const base=process.env.TEST_BASE_URL||'http://127.0.0.1:3100';
fs.mkdirSync('artifacts',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/portal',{waitUntil:'networkidle'});
 await page.getByText('19 Dec 2026',{exact:true}).first().waitFor();
 await page.screenshot({path:'artifacts/portal-desktop.png',fullPage:true});
 console.log('Desktop:',await page.title());
 await page.getByRole('button',{name:'My guests',exact:true}).click();
 await page.getByRole('textbox',{name:'Invitation code',exact:true}).fill('ANL-NOT-A-REAL-CODE');
 await page.getByRole('button',{name:'Open invitation',exact:true}).click();
 await page.getByText('Invitation not found',{exact:true}).waitFor();
 console.log('Invalid invitation rejected visibly');
 await page.getByRole('button',{name:'Event details',exact:true}).click();
 await page.getByRole('heading',{name:'All the little details.'}).waitFor();
 await page.getByRole('button',{name:'AI helpdesk',exact:true}).click();
 await page.getByRole('textbox',{name:'Your question'}).fill('Where can we park?');
 await page.getByRole('button',{name:'Send question'}).click();
 await page.getByRole('log').getByText(/Gate 2/).waitFor({timeout:70000});
 console.log('Helpdesk: grounded parking answer rendered');
 await page.screenshot({path:'artifacts/helpdesk-desktop.png',fullPage:true});
 await page.goto(base+'/admin',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Behind the scenes.'}).waitFor();
 await page.screenshot({path:'artifacts/staff-login.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'/portal',{waitUntil:'networkidle'});
 await page.screenshot({path:'artifacts/portal-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw new Error('Mobile page overflows horizontally');
 await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 await page.getByRole('button',{name:'My invitation',exact:true}).click();
 await page.getByRole('textbox',{name:'Invitation code',exact:true}).waitFor();
 console.log('Mobile: navigation, form and horizontal layout passed');
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('Browser checks passed. Screenshots saved to artifacts/.');
} finally {await browser.close();}
